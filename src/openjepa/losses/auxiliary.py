"""Вспомогательные функции потерь для JEPA.

Здесь собраны два приёма, без которых JEPA-модель мира не годится для
планирования. Оба используют **привилегированную информацию** — то, что
доступно в симуляторе при обучении, но не нужно на инференсе.
"""

from __future__ import annotations

import torch


def variance_floor(
    z: torch.Tensor,
    target: float = 1.0,
    eps: float = 1e-6,
) -> torch.Tensor:
    """Штраф за слишком малую дисперсию по каждой оси латента.

    Зачем. У SIGReg есть **седловая точка в `z = 0`**: при `z_i = 0` все
    `cos(t·z) = 1` и `sin(t·z) = 0`, статистика равна константе, а её
    градиент по `z` — нулю. Если сеть может дёшево уменьшить ошибку
    предсказания, сжимая латент, она это сделает и останется там навсегда.

    Это та причина, по которой в референсной реализации LeJEPA стоит
    `BatchNorm1d` в проекторе: BN нормирует по батчу, поэтому состояние
    «все сэмплы одинаковые» недостижимо.

    Но у BN есть цена: она хранит running-статистики, и в `eval()` латент
    получается **другим**, чем в `train()`. На нашем прогоне это давало
    `pred_loss` 0.24 против 3.25 и ломало перенос пробы `z → p`
    (проба училась на train-латентах, а в инференсе видела eval-латент).

    `variance_floor` решает ту же задачу без состояния: он требует, чтобы
    стандартное отклонение по каждой оси было не меньше `target`. Работает
    одинаково в `train` и `eval`, при любом размере батча, включая 1.

    Args:
        z: (..., D).
        target: желаемое минимальное std по оси.
        eps: защита от нуля.

    Returns:
        Скаляр. 0, если все оси достаточно «широкие».
    """
    zp = z.reshape(-1, z.shape[-1]).float()
    if zp.shape[0] < 2:
        return z.new_zeros(())
    std = zp.std(dim=0)
    return torch.relu(target - std).pow(2).mean()


def metric_loss(
    z: torch.Tensor,
    positions: torch.Tensor,
    n_pairs: int = 64,
    eps: float = 1e-6,
) -> torch.Tensor:
    """Требует, чтобы латентное расстояние было пропорционально реальному.

    Зачем. Планировщик минимизирует `‖z_t − z_goal‖²`. Если это число не
    связано с расстоянием до цели, CEM оптимизирует шум: в латенте план
    идеален, в мире — нет. Ни `pred_loss`, ни SIGReg этого не гарантируют.

    Как. Берём случайные пары точек, считаем отношение `‖Δz‖ / ‖Δp‖` и
    минимизируем **коэффициент вариации** этого отношения:

        L = std(r) / (mean(r) + eps),    r = ‖Δz‖ / ‖Δp‖

    Почему коэффициент вариации, а не `|‖Δz‖ − α‖Δp‖|`:

    * первая форма **безразмерна**, поэтому её масштаб не зависит от
      масштаба латента, и она не конкурирует с SIGReg за дисперсию;
    * вторая форма в абсолютных единицах легко доминирует над `pred_loss`
      (на нашем прогоне давала 7.4 против 0.27) и разрушает обучение.

    `mean(r)` не detach'ится, но форма безразмерная, поэтому «схлопнуть»
    латент в ноль нельзя: при `‖Δz‖ → 0` числитель и знаменатель падают
    одновременно, и L не уменьшается.

    Args:
        z: (..., D) латенты.
        positions: (..., P) реальные координаты (P обычно 2).
        n_pairs: сколько случайных пар брать (дешевле, чем все `N²`).
        eps: защита от деления на ноль.

    Returns:
        Скаляр. 0 означает идеальную линейную связь.
    """
    if positions is None:
        return z.new_zeros(())

    zp = z.reshape(-1, z.shape[-1]).float()
    pp = positions.reshape(-1, positions.shape[-1]).float()
    n = zp.shape[0]
    if n < 2:
        return z.new_zeros(())

    k = min(n_pairs, n)
    i = torch.randint(0, n, (k,), device=zp.device)
    j = torch.randint(0, n, (k,), device=zp.device)

    dz = (zp[i] - zp[j]).norm(dim=-1)
    dp = (pp[i] - pp[j]).norm(dim=-1)
    mask = dp > 1.0            # пары почти в одной точке ничего не говорят
    if not mask.any():
        return z.new_zeros(())

    ratio = dz[mask] / (dp[mask] + eps)
    return ratio.std() / (ratio.mean().abs() + eps)


def inverse_dynamics_loss(
    inverse: torch.nn.Module,
    z: torch.Tensor,
    actions: torch.Tensor,
) -> torch.Tensor:
    """Ошибка восстановления действия по паре соседних латентов.

    Зачем. Основная потеря JEPA поощряет выбрасывать всё, что не помогает
    предсказанию. Факторы, управляемые действием, но трудно предсказуемые
    (например, горизонтальная позиция под гравитацией), энкодер выбросит —
    и латент станет бесполезным для планирования.

    Как. Требуем, чтобы действие восстанавливалось из `(z_t, z_{t+1})`.
    Это вынуждает латент сохранять всё, на что действие влияет.

    Тот же приём: H-JEPA (arXiv:2610.06805), DINO-WM (arXiv:2411.04983).

    Args:
        inverse: голова `InverseDynamics`.
        z: (B,T,D) последовательность латентов.
        actions: (B,T-1,A).

    Returns:
        Скаляр (smooth L1).
    """
    b, t, d = z.shape
    n = b * (t - 1)
    pred = inverse(z[:, :-1].reshape(n, d), z[:, 1:].reshape(n, d))
    return torch.nn.functional.smooth_l1_loss(pred, actions.reshape(n, -1))
